-- Гражданство игрока — одна страна, как называть на сайте («Россия», «Черногория»). Заполнено из Викиданных
-- (local/players_wiki_citizenship_initials.sql): исторические государства (СССР, Сербия и Черногория) — только если
-- другого нет, двойное — по взрослой сборной, нет взрослой — по молодёжной. Правится в карточке игрока в админке.

alter table player add column citizenship text check (citizenship is null or btrim(citizenship) <> '');

comment on column player.citizenship is
  'Гражданство — одна страна, как на сайте («Россия»). Двойное — по сборной, за которую играл; пусто — неизвестно.';
