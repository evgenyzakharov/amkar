-- Видео к матчу: полный матч или обзор, ссылкой на YouTube или ВК. У матча может быть несколько видео.
-- Сайт определяется по адресу сам; другие сайты не принимаем — понадобятся, расширим проверку новой миграцией.

create table match_video (
  id         int generated by default as identity primary key,
  match_id   int not null references match on delete cascade,
  kind       text not null check (kind in ('full', 'highlights')),
  url        text not null check (url ~ '^https://'),
  site       text generated always as (
    case
      when url ~* '^https://([a-z0-9-]+\.)*(youtube\.com|youtu\.be)/' then 'youtube'
      when url ~* '^https://([a-z0-9-]+\.)*(vk\.com|vkvideo\.ru)/' then 'vk'
    end
  ) stored,
  title      text check (btrim(title) <> ''),
  created_at timestamptz not null default now(),
  unique (match_id, url),
  constraint match_video_youtube_or_vk check (site is not null)
);
comment on table match_video is 'Видео матча: полный матч (full) или обзор (highlights), ссылкой на YouTube или ВК.';
comment on column match_video.site is 'youtube или vk — по адресу ссылки.';
comment on column match_video.title is 'Подпись, например «ТВ-трансляция».';
create index on match_video (match_id);

alter table match_video enable row level security;
create policy "public read" on match_video for select to anon, authenticated using (true);
create policy "admin insert" on match_video for insert to authenticated with check ((select is_admin()));
create policy "admin update" on match_video for update to authenticated using ((select is_admin())) with check ((select is_admin()));
create policy "admin delete" on match_video for delete to authenticated using ((select is_admin()));
revoke all on match_video from anon, authenticated;
grant select on match_video to anon, authenticated;
grant insert, update, delete on match_video to authenticated;
grant usage on all sequences in schema public to authenticated;
