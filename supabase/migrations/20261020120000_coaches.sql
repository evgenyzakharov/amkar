do $$
declare
  v text;
begin
  foreach v in array array['player_debut', 'coach_player_stats'] loop
    execute format('revoke all on %I from anon, authenticated', v);
    execute format('grant select on %I to anon, authenticated', v);
  end loop;
end
$$;
