-- Страница «Тренеры»: сроки работы тренеров и view для карточки тренера.
--
-- coach_tenure — назначения и увольнения: у тренера может быть несколько сроков (Рахимов, Божович, Хузин).
-- Лента «Эпохи» и период в карточке берутся отсюда; у тренера без сроков — по первому и последнему матчу.
-- Остальная статистика тренера (очки, серии, ачивки) считается на сайте из матчей: их около тысячи.
--
-- Во view — только официальные матчи (без товарищеских). «Сыграл» — как в player_season_stats:
-- вышел в старте, на замену или есть минуты.

create table coach_tenure (
  id        int generated by default as identity primary key,
  coach_id  int not null references coach on delete cascade,
  from_date date not null,
  to_date   date,
  notes     text,
  check (to_date is null or to_date >= from_date)
);
comment on table coach_tenure is 'Срок работы главного тренера: назначение и увольнение. to_date пусто — работает сейчас.';
create index on coach_tenure (coach_id);

alter table coach_tenure enable row level security;
create policy "public read" on coach_tenure for select to anon, authenticated using (true);
create policy "admin insert" on coach_tenure for insert to authenticated with check ((select is_admin()));
create policy "admin update" on coach_tenure for update to authenticated using ((select is_admin())) with check ((select is_admin()));
create policy "admin delete" on coach_tenure for delete to authenticated using ((select is_admin()));
grant select on coach_tenure to anon, authenticated;
grant insert, update, delete on coach_tenure to authenticated;

-- ===========================================================================
-- Первый официальный матч игрока за «Амкар»
-- ===========================================================================

create view player_debut with (security_invoker = true) as
select distinct on (ap.player_id)
  ap.player_id,
  p.display_name,
  p.academy,
  m.id as match_id,
  m.match_date,
  m.season_id,
  s.label as season_label,
  s.start_year,
  m.coach_id
from appearance ap
join match m on m.id = ap.match_id
join competition c on c.id = m.competition_id
join season s on s.id = m.season_id
join player p on p.id = ap.player_id
where c.kind <> 'friendly'
  and (ap.minutes > 0 or ap.role in ('start', 'sub'))
order by ap.player_id, s.start_year, s.end_year, m.match_date nulls last, m.seq;

comment on view player_debut is
  'Первый официальный матч игрока за «Амкар» (дебют) и тренер того матча. Порядок — сезон, дата, номер матча в сезоне.';

-- ===========================================================================
-- Игроки при тренере: матчи, минуты, голы
-- ===========================================================================

create view coach_player_stats with (security_invoker = true) as
with apps as (
  select m.coach_id, ap.player_id, count(*)::int as games, coalesce(sum(ap.minutes), 0)::int as minutes
  from appearance ap
  join match m on m.id = ap.match_id
  join competition c on c.id = m.competition_id
  where m.coach_id is not null
    and c.kind <> 'friendly'
    and (ap.minutes > 0 or ap.role in ('start', 'sub'))
  group by m.coach_id, ap.player_id
),
goals as (
  select m.coach_id, g.scorer_id as player_id, count(*)::int as goals
  from goal g
  join match m on m.id = g.match_id
  join competition c on c.id = m.competition_id
  where m.coach_id is not null
    and c.kind <> 'friendly'
    and g.side = 'amkar' and g.kind <> 'own_goal' and g.scorer_id is not null
  group by m.coach_id, g.scorer_id
)
select
  coalesce(a.coach_id, g.coach_id) as coach_id,
  coalesce(a.player_id, g.player_id) as player_id,
  p.display_name,
  coalesce(a.games, 0) as games,
  coalesce(a.minutes, 0) as minutes,
  coalesce(g.goals, 0) as goals
from apps a
full join goals g on g.coach_id = a.coach_id and g.player_id = a.player_id
join player p on p.id = coalesce(a.player_id, g.player_id);

comment on view coach_player_stats is
  'Игрок при тренере: официальные матчи, минуты и голы по таблице goal (без автоголов). Для «Его игроки» и «Его бомбардиры».';

-- ===========================================================================
-- Только чтение
