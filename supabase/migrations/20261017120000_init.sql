create table season (
  id          int generated by default as identity primary key,
  label       text not null unique,
  start_year  smallint not null,
  end_year    smallint not null,
  division    text,
  tier        smallint check (tier between 1 and 5),
  final_place smallint check (final_place > 0),
  teams_count smallint check (teams_count > 0),
  notes       text,
  check (end_year between start_year and start_year + 1),
  check (final_place is null or teams_count is null or final_place <= teams_count)
);
comment on table season is 'Сезон основной команды. label как на сайте: «1995», «2011/12».';
comment on column season.division is 'Лига чемпионата в этом сезоне, как её называть на сайте.';
comment on column season.tier is 'Уровень лиги: 1 — высший дивизион.';

create table competition (
  id   int generated by default as identity primary key,
  name text not null unique,
