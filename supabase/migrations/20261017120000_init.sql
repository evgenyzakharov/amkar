-- ===========================================================================
-- Служебное: админы и updated_at
-- ===========================================================================

create table admins (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);
comment on table admins is 'Кто может менять данные. Добавлять вручную: insert into admins (user_id) select id from auth.users where email = ''…''';

-- security definer: функция читает admins, хотя самой таблицы через API не видно никому
create function is_admin() returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.admins where user_id = (select auth.uid()));
$$;

create function set_updated_at() returns trigger
language plpgsql set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

