create table match (
  id             int generated by default as identity primary key,
  season_id      int not null references season,
  competition_id int not null references competition,
  seq            smallint not null check (seq > 0),
  round          text,
  match_date     date,
  venue          text check (venue in ('home', 'away', 'neutral')),
  opponent_id    int references team,
  opponent_raw   text,
  result         text check (result in ('W', 'D', 'L')),
  goals_for      smallint check (goals_for >= 0),
  goals_against  smallint check (goals_against >= 0),
  extra_time     boolean not null default false,
  pens_for       smallint check (pens_for >= 0),
  pens_against   smallint check (pens_against >= 0),
  coach_id       int references coach,
  formation      text,
  notes          text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  -- deferrable: чтобы вставить пропущенный матч в середину сезона и сдвинуть номера одной транзакцией
  unique (season_id, seq) deferrable initially deferred,
  check (opponent_id is not null or opponent_raw is not null),
  check ((goals_for is null) = (goals_against is null)),
  check ((pens_for is null) = (pens_against is null)),
  check (pens_for is null or (goals_for is not null and goals_for = goals_against and pens_for <> pens_against)),
  -- результат сходится со счётом; при серии пенальти допустима и ничья, и итог серии
  check (result is null or goals_for is null or pens_for is not null
         or result = case when goals_for > goals_against then 'W'
                          when goals_for < goals_against then 'L'
                          else 'D' end),
  check (result is null or pens_for is null
         or result in ('D', case when pens_for > pens_against then 'W' else 'L' end))
);
comment on table match is 'Матч основной команды. Для старых матчей пока известен только result (из цвета в Excel), остальное дозаполняется.';
comment on column match.seq is 'Порядковый номер матча в сезоне.';
comment on column match.round is 'Тур или стадия: «17», «1/16 финала».';
comment on column match.opponent_raw is 'Соперник как в Excel, пока не сопоставлен с team.';
comment on column match.result is 'W — победа, D — ничья, L — поражение.';
comment on column match.goals_for is 'Голы «Амкара» без серии пенальти.';
create index on match (opponent_id);
create index on match (coach_id);
create index on match (match_date);

create table appearance (
  match_id           int not null references match on delete cascade,
  player_id          int not null references player,
  role               text check (role in ('start', 'sub', 'bench')),
  minutes            smallint check (minutes between 0 and 130),
  minute_on          smallint check (minute_on between 1 and 130),
  minute_off         smallint check (minute_off between 1 and 130),
  replaced_player_id int,
  injured            boolean not null default false,
  sent_off           boolean not null default false,
  primary key (match_id, player_id),
  -- заменённый игрок должен быть в заявке того же матча
  foreign key (match_id, replaced_player_id) references appearance (match_id, player_id) deferrable initially deferred,
  check (role is distinct from 'bench' or coalesce(minutes, 0) = 0),
  check (role is not distinct from 'sub' or (minute_on is null and replaced_player_id is null)),
  check (replaced_player_id is distinct from player_id),
  check (minute_off is null or minute_on is null or minute_off >= minute_on)
);
comment on table appearance is 'Игрок в заявке на матч. Нет строки — не был в заявке.';
comment on column appearance.role is 'start — в старте, sub — вышел на замену, bench — в запасе и не вышел. Пусто — неизвестно (старые матчи, где в Excel только минуты).';
comment on column appearance.minutes is 'Минуты на поле, 0 — не выходил.';
comment on column appearance.minute_on is 'Минута выхода на замену.';
comment on column appearance.minute_off is 'Минута, когда заменён или удалён.';
comment on column appearance.replaced_player_id is 'Кого заменил (для role = sub).';
comment on column appearance.injured is 'Получил травму в этом матче.';
comment on column appearance.sent_off is 'Удалён в этом матче.';
create index on appearance (player_id);

create table absence (
  match_id  int not null references match on delete cascade,
  player_id int not null references player,
  reason    text not null check (reason in ('injury', 'suspension')),
  primary key (match_id, player_id)
);
comment on table absence is 'Пропуск матча из-за травмы или дисквалификации.';
create index on absence (player_id);

create table goal (
  id          int generated by default as identity primary key,
  match_id    int not null references match on delete cascade,
  side        text not null check (side in ('amkar', 'opponent')),
  minute      smallint check (minute between 1 and 130),
  added_time  smallint check (added_time between 1 and 30),
  kind        text not null default 'open_play' check (kind in ('open_play', 'penalty', 'own_goal')),
  scorer_id   int references player,
  scorer_name text,
  assist_id   int references player,
  check (scorer_id is null or scorer_name is null),
  -- игрок «Амкара» — автор нашего гола или автогола в наши ворота, игрок соперника — наоборот
  check (scorer_id is null or (side = 'amkar') = (kind <> 'own_goal')),
  check (scorer_name is null or (side = 'opponent') = (kind <> 'own_goal')),
  check (assist_id is null or (side = 'amkar' and kind <> 'own_goal')),
  check (added_time is null or minute in (45, 90, 105, 120))
);
comment on table goal is 'Голы матча, в том числе пропущенные. Серия пенальти сюда не входит.';
comment on column goal.side is 'Чей гол: amkar — забил «Амкар», opponent — пропустил.';
comment on column goal.added_time is 'Компенсированное время: 90+3 — это minute = 90, added_time = 3.';
comment on column goal.scorer_id is 'Игрок «Амкара»: автор гола или автогола.';
comment on column goal.scorer_name is 'Игрок соперника текстом: автор гола или автогола.';
create index on goal (match_id);
create index on goal (scorer_id);
create index on goal (assist_id);

create table player_season_totals (
  season_id      int not null,
  player_id      int not null,
  competition_id int not null references competition,
  goals          smallint check (goals >= 0),
  assists        smallint check (assists >= 0),
  goals_conceded smallint check (goals_conceded >= 0),
  primary key (season_id, player_id, competition_id),
  foreign key (season_id, player_id) references squad_member (season_id, player_id)
);
comment on table player_season_totals is 'Голы и передачи за сезон из Excel — по матчам их там нет. Когда сезон заполнен в goal, сверяем с ним.';
comment on column player_season_totals.goals_conceded is 'Пропущенные мячи вратаря (в Excel записаны минусом в столбце голов).';

