-- Названия клуба по годам: «Уралмаш» до 2002, «Урал» с 2003.
-- Клуб — одна строка team, его матчи считаются вместе; на сайте у матча — название, которое клуб носил в сезон матча.
-- Год — год начала сезона (season.start_year): у сезона «2011/12» это 2011.

create table team_name (
  id        int generated by default as identity primary key,
  team_id   int not null references team on delete cascade,
  name      text not null check (btrim(name) <> ''),
  from_year smallint check (from_year between 1900 and 2100),
  to_year   smallint check (to_year between 1900 and 2100),
  check (from_year is null or to_year is null or from_year <= to_year)
);
comment on table team_name is 'Прежние названия клуба по годам. Нет подходящей строки — показывается team.name.';
comment on column team_name.from_year is 'С какого года (начала сезона) так назывался; пусто — с самого начала.';
comment on column team_name.to_year is 'По какой год включительно; пусто — до сих пор.';
create index on team_name (team_id);

alter table team_name enable row level security;
create policy "public read" on team_name for select to anon, authenticated using (true);
create policy "admin insert" on team_name for insert to authenticated with check ((select is_admin()));
create policy "admin update" on team_name for update to authenticated using ((select is_admin())) with check ((select is_admin()));
create policy "admin delete" on team_name for delete to authenticated using ((select is_admin()));
revoke all on team_name from anon, authenticated;
grant select on team_name to anon, authenticated;
grant insert, update, delete on team_name to authenticated;
grant usage on all sequences in schema public to authenticated;

-- Название клуба на заданный год: из team_name, иначе team.name
create function team_name_in(p_team_id int, p_year int) returns text
language sql stable set search_path = ''
as $$
  select coalesce(
    (select tn.name from public.team_name tn
     where tn.team_id = p_team_id
       and (tn.from_year is null or tn.from_year <= p_year)
       and (tn.to_year is null or tn.to_year >= p_year)
     order by tn.from_year desc nulls last, tn.id desc
     limit 1),
    (select t.name from public.team t where t.id = p_team_id));
$$;

-- Вычисляемые столбцы для PostgREST: match?select=…,opponent_name и transfer?select=…,other_team_name.
-- Клуб не выбран из справочника — текст из таблицы автора.
create function opponent_name(m match) returns text
language sql stable set search_path = ''
as $$
  select coalesce(
    public.team_name_in(m.opponent_id, (select s.start_year from public.season s where s.id = m.season_id)),
    m.opponent_raw);
$$;
comment on function opponent_name(match) is 'Соперник так, как он назывался в сезон матча.';

create function other_team_name(t transfer) returns text
language sql stable set search_path = ''
as $$
  select coalesce(
    public.team_name_in(t.other_team_id, (select s.start_year from public.season s where s.id = t.season_id)),
    t.other_team_raw);
$$;
comment on function other_team_name(transfer) is 'Клуб трансфера так, как он назывался в сезон трансфера.';

-- Явно: если «Automatically expose new tables» выключено, Supabase не выдаёт права на новые функции
revoke execute on function team_name_in(int, int), opponent_name(match), other_team_name(transfer) from public;
grant execute on function team_name_in(int, int), opponent_name(match), other_team_name(transfer) to anon, authenticated;
